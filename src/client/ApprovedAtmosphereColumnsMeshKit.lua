-- P4: genuine approved creator-owned forged columns replace the large
-- primitive atmospheric pillar/spine bodies, never their navigation lights.
-- One existing scenery LOD sampler owns this visual-only substitution.
local ReplicatedStorage = game:GetService("ReplicatedStorage")

local Kit = {}
local IDS = {
    Classic = 91626128452597,
    Towers = 107521411452905,
    Crossroads = 93993697329658,
    Orbital = 119010829781313,
    Harbor = 76194593490199,
}
local PILLAR_HEIGHT = {
    Classic = 8, Towers = 18, Crossroads = 11, Orbital = 13,
    Harbor = 11,
}
local SPINE_HEIGHT = {
    Classic = 11, Towers = 23, Crossroads = 13, Orbital = 17,
    Harbor = 15,
}
local BUDGET = {
    -- One near-camera authored column on Low. Native bodies are always
    -- retained and restored as soon as visual pressure reaches level 1.
    Low = {cap = 1, distance = 175},
    Medium = {cap = 2, distance = 230},
    High = {cap = 4, distance = 390},
}
local PILLAR_OFFSETS = {
    Vector3.new(-41, 0, -41), Vector3.new(41, 0, -41),
    Vector3.new(-41, 0, 41), Vector3.new(41, 0, 41),
}
local SPINE_CORNERS = {
    {-1, -1}, {1, -1}, {-1, 1}, {1, 1},
}
local bucket = Instance.new("Folder")
bucket.Name = "ApprovedAtmosphereColumnsLocal"
bucket:SetAttribute("CosmeticOnly", true)
bucket.Parent = workspace
local mounted = {}
local activeArena = nil

-- If another local budget owner destroys an approved clone between
-- camera samples, restore the native body immediately, not one LOD
-- interval later. One event on the existing local folder only.

local function remove(native)
    local entry = mounted[native]
    if not entry then return end
    mounted[native] = nil
    for _, connection in ipairs(entry.connections) do
        connection:Disconnect()
    end
    if native.Parent == entry.folder and native.Transparency == 1 then
        native.Transparency = entry.original
    end
    entry.model:Destroy()
end

bucket.ChildRemoved:Connect(function(child)
    if not child:IsA("Model") then return end
    for native, entry in pairs(mounted) do
        if entry.model == child then
            remove(native)
            break
        end
    end
end)

local function removeAll()
    local items = {}
    for native in pairs(mounted) do items[#items + 1] = native end
    for _, native in ipairs(items) do remove(native) end
end

local function sourceFor(variant)
    local id = IDS[variant]
    if not id then return nil end
    local holder = ReplicatedStorage:FindFirstChild(
        "ApprovedLargeStructureTemplates")
    if not holder or not holder:IsA("Folder")
        or holder.Parent ~= ReplicatedStorage
        or holder:GetAttribute("OwnerVerified") ~= true then
        return nil
    end
    local model = holder:FindFirstChild(variant)
    if not model or not model:IsA("Model") or model.Parent ~= holder
        or model:GetAttribute("OwnerVerified") ~= true
        or model:GetAttribute("OriginalLargeStructure3D") ~= true
        or model:GetAttribute("CosmeticOnly") ~= true
        or model:GetAttribute("Original3DAssetId") ~= id then
        return nil
    end
    local count = 0
    for _, part in ipairs(model:GetDescendants()) do
        if part:IsA("BasePart") then
            if not part:IsA("MeshPart") or part.CanCollide
                or part.CanTouch or part.CanQuery then return nil end
            count += 1
        elseif part:IsA("LuaSourceContainer") then
            return nil
        end
    end
    if count ~= 7 then return nil end
    local _, size = model:GetBoundingBox()
    local long, short = math.max(size.X, size.Z),
        math.min(size.X, size.Z)
    if size.Y < 13.4 or size.Y > 15.1
        or long < 1.6 or long > 2.8
        or short < 1.5 or short > 2.7 then return nil end
    return model, holder, id, size
end

-- Exact native visual generated by ArenaAtmosphere.server.lua.
-- This refuses arbitrary map objects, physical surfaces and gameplay cues.
local function originalAt(arena, kind, index)
    if not arena or not arena:IsA("Folder") or arena.Name ~= "Arena"
        or not arena.Parent or arena.Parent.Name ~= "GeneratedMap"
        or arena.Parent.Parent ~= workspace then return nil end
    local variant = arena:GetAttribute("VariantId")
    if not IDS[variant] then return nil end
    local base = arena:FindFirstChild("Base")
    local folder = arena:FindFirstChild("Atmosphere")
    if not base or not base:IsA("BasePart") or base.Parent ~= arena
        or not base.Anchored or not base.CanCollide
        or base.Size.X < 318 or base.Size.Z < 318
        or not folder or not folder:IsA("Folder")
        or folder.Parent ~= arena
        or folder:GetAttribute("VariantId") ~= variant
        or folder:GetAttribute("VisualVersion") ~= 2 then
        return nil
    end
    if type(index) ~= "number" or index < 1 or index > 4
        or index ~= math.floor(index) then return nil end

    local harbor = variant == "Harbor"
    local height, position, size
    if kind == "AtmospherePillar" then
        height = PILLAR_HEIGHT[variant] + (index % 2) * 3
        position = base.Position + PILLAR_OFFSETS[index]
            + Vector3.new(0, height * 0.5 + 1, 0)
        size = harbor and Vector3.new(height, 1.65, 1.65)
            or Vector3.new(1.25, height, 1.25)
    elseif kind == "SilhouetteSpine" then
        height = SPINE_HEIGHT[variant]
        local corner = SPINE_CORNERS[index]
        position = base.Position + Vector3.new(
            corner[1] * (base.Size.X * 0.5 + 10),
            height * 0.5,
            corner[2] * (base.Size.Z * 0.5 + 10))
        size = harbor and Vector3.new(height, 2.4, 2.4)
            or Vector3.new(2.4, height, 2.4)
    else
        return nil
    end
    local native = folder:FindFirstChild(kind .. tostring(index))
    if not native or not native:IsA("Part")
        or native.Parent ~= folder
        or not native.Anchored or native.CanCollide
        or native.CanTouch or native.CanQuery
        or native.Shape ~= (harbor and Enum.PartType.Cylinder
            or Enum.PartType.Block)
        or (native.Size - size).Magnitude > .08
        or (native.Position - position).Magnitude > .12
        or native.Transparency ~= 1
            and math.abs(native.Transparency -
                (kind == "AtmospherePillar" and .08 or .04)) > .035 then
        return nil
    end
    -- Colored signal caps and bands remain native and must be present.
    local marker = folder:FindFirstChild(
        (kind == "AtmospherePillar" and "AtmosphereBeacon"
            or "SilhouetteCap") .. tostring(index))
    if not marker or not marker:IsA("Part")
        or marker.Parent ~= folder or not marker.Anchored
        or marker.CanCollide or marker.CanTouch or marker.CanQuery then
        return nil
    end
    if kind == "SilhouetteSpine" then
        for level = 1, 2 do
            local band = folder:FindFirstChild(
                "SilhouetteBand" .. tostring(index) .. "_" .. tostring(level))
            if not band or not band:IsA("Part")
                or band.Parent ~= folder or not band.Anchored
                or band.CanCollide or band.CanTouch
                or band.CanQuery then return nil end
        end
    end
    return native, folder, height, size
end

local function valid(entry)
    if entry.arena ~= activeArena
        or entry.model.Parent ~= bucket
        or entry.source.Parent ~= entry.holder
        or entry.holder.Parent ~= ReplicatedStorage
        or entry.source:GetAttribute("Original3DAssetId") ~= entry.id
        or #entry.pieces ~= 7 then return false end
    local native, folder, height = originalAt(
        entry.arena, entry.kind, entry.index)
    if native ~= entry.native or folder ~= entry.folder
        or height ~= entry.height then return false end
    for _, part in ipairs(entry.pieces) do
        if not part:IsDescendantOf(entry.model)
            or part.CanCollide or part.CanTouch or part.CanQuery then
            return false
        end
    end
    return true
end

-- Reject camera-nearest candidates which cannot physically hold the
-- source sculpt BEFORE claiming one of the scarce Low/Medium slots.
-- This uses only dimensions of the already owner-verified source and the
-- exact server-authored native. It never stretches or shrinks a mesh axis.
local function candidateFit(sourceSize, kind, variant, height)
    if typeof(sourceSize) ~= "Vector3" or sourceSize.Y <= 0 then
        return nil
    end
    local scale = height / sourceSize.Y
    if scale < .54 or scale > 1.75 then return nil end
    local nativeWidth = kind == "AtmospherePillar"
        and (variant == "Harbor" and 1.65 or 1.25) or 2.4
    local maxWidth = math.max(2.4, nativeWidth * 2.1)
    -- A small allowance avoids rounding-related false rejection; final
    -- mounted GetBoundingBox still enforces the strict actual width.
    if sourceSize.X * scale > maxWidth + .08
        or sourceSize.Z * scale > maxWidth + .08 then
        return nil
    end
    return scale, maxWidth
end

local function mount(arena, item, source, holder, id, sourceSize)
    local native, folder, height = originalAt(
        arena, item.kind, item.index)
    if not native or native ~= item.native then return end
    local scale, maxWidth = candidateFit(
        sourceSize, item.kind, arena:GetAttribute("VariantId"), height)
    if not scale then return end
    local clone = source:Clone()
    if not pcall(function() clone:ScaleTo(scale) end) then
        clone:Destroy()
        return
    end
    local frame, bounds = clone:GetBoundingBox()
    -- The actual scaled clone remains the final authority: if it grows
    -- too fat for the original footprint, native visuals remain visible.
    if math.abs(bounds.Y - height) > .13
        or bounds.X > maxWidth or bounds.Z > maxWidth then
        clone:Destroy()
        return
    end
    local target = CFrame.new(native.Position)
    local pieces = {}
    for _, part in ipairs(clone:GetDescendants()) do
        if part:IsA("BasePart") then
            if not part:IsA("MeshPart") then
                clone:Destroy()
                return
            end
            part.CFrame = target * frame:ToObjectSpace(part.CFrame)
            part.Anchored = true
            part.Massless = true
            part.CanCollide = false
            part.CanTouch = false
            part.CanQuery = false
            part.CastShadow = false
            part:SetAttribute("CosmeticOnly", true)
            pieces[#pieces + 1] = part
        end
    end
    if #pieces ~= 7 or source.Parent ~= holder
        or not originalAt(arena, item.kind, item.index) then
        clone:Destroy()
        return
    end
    clone.Name = "ApprovedAtmosphere3D_" .. item.kind .. item.index
    clone:SetAttribute("CosmeticOnly", true)
    clone:SetAttribute("Original3DAssetId", id)
    clone.Parent = bucket
    local entry = {
        arena = arena, kind = item.kind, index = item.index,
        native = native, folder = folder, height = height,
        model = clone, source = source, holder = holder, id = id,
        pieces = pieces, original = native.Transparency,
        connections = {},
    }
    mounted[native] = entry
    if not valid(entry) then remove(native); return end
    native.Transparency = 1

    local function check()
        if mounted[native] == entry and not valid(entry) then
            remove(native)
        end
    end
    for _, object in ipairs({native, folder, arena, source, clone}) do
        entry.connections[#entry.connections + 1] =
            object.AncestryChanged:Connect(check)
    end
    entry.connections[#entry.connections + 1] =
        native:GetPropertyChangedSignal("Size"):Connect(check)
    entry.connections[#entry.connections + 1] =
        native:GetPropertyChangedSignal("CFrame"):Connect(check)
    entry.connections[#entry.connections + 1] =
        source.DescendantRemoving:Connect(function(part)
            if part:IsA("MeshPart") then remove(native) end
        end)
    entry.connections[#entry.connections + 1] =
        clone.DescendantRemoving:Connect(function(part)
            if part:IsA("MeshPart") then remove(native) end
        end)
end

function Kit.sync(arena, cameraPoint, tier, cameraReady, touch, pressure)
    if arena ~= activeArena then
        removeAll()
        activeArena = arena
    end
    local spec = BUDGET[tier] or BUDGET.Low
    local stress = tonumber(pressure) or 0
    if stress ~= stress or math.abs(stress) == math.huge then stress = 2 end
    stress = math.clamp(math.floor(stress), 0, 2)
    local cap = spec.cap
    if tier == "High" and touch then cap = 3 end
    if stress == 1 then cap = math.floor(cap / 2) end
    -- Low has no optional reserve under pressure; keep only the native
    -- one-Part body instead of the seven-piece authored sculpture.
    if tier == "Low" and stress >= 1 then cap = 0 end
    if stress >= 2 then cap = 0 end
    if not cameraReady or typeof(cameraPoint) ~= "Vector3" then cap = 0 end
    local variant = arena and arena:GetAttribute("VariantId")
    local source, holder, id, size = sourceFor(variant)
    if not source then cap = 0 end

    local candidates = {}
    if cap > 0 then
        -- Both families compete for the same cap, but only shapes that
        -- can actually fit this source should consume a ranked slot.
        for _, kind in ipairs({"AtmospherePillar", "SilhouetteSpine"}) do
            for index = 1, 4 do
                local native, _, height = originalAt(arena, kind, index)
                if native and candidateFit(size, kind, variant, height) then
                    local held = mounted[native] ~= nil
                    local distance = (native.Position - cameraPoint).Magnitude
                    if distance <= spec.distance + (held and 22 or 0) then
                        candidates[#candidates + 1] = {
                            native = native, kind = kind, index = index,
                            score = distance + (kind == "SilhouetteSpine"
                                and 15 or 0) - (held and 11 or 0),
                        }
                    end
                end
            end
        end
        table.sort(candidates, function(a, b)
            if a.score ~= b.score then return a.score < b.score end
            return a.kind .. a.index < b.kind .. b.index
        end)
    end
    local wanted = {}
    for i = 1, math.min(cap, #candidates) do
        wanted[candidates[i].native] = candidates[i]
    end
    local obsolete = {}
    for native, entry in pairs(mounted) do
        if not wanted[native] or entry.source ~= source
            or not valid(entry) then
            obsolete[#obsolete + 1] = native
        else
            native.Transparency = 1
        end
    end
    for _, native in ipairs(obsolete) do remove(native) end
    for native, item in pairs(wanted) do
        if not mounted[native] then
            mount(arena, item, source, holder, id, size)
        end
    end
end

function Kit.count()
    local total = 0
    for _, entry in pairs(mounted) do
        if valid(entry) then total += 1 end
    end
    return total
end

function Kit.replacedNativeCount()
    local total = 0
    for native, entry in pairs(mounted) do
        if valid(entry) and native.Transparency == 1 then total += 1 end
    end
    return total
end

return Kit
