#!/usr/bin/env python3
"""P4: genuine creator-approved Towers machinery, source-level regression.

This checks both the actual 7-material OBJ/glTF source and the safe Roblox
runtime contract, not unverified Engine FPS, streaming or screenshots.
"""
from pathlib import Path
import json
import re
import subprocess
import sys
import tempfile

ROOT=Path(__file__).resolve().parents[1]
NAME="variant_towers_sculpted_machinery"
ID="72143366927826"
RUN=42861370182
REG=json.loads((ROOT/"assets/source/roblox-asset-registry.json").read_text())
LOADER=(ROOT/"src/server/PremiumVariantTowersLandmarkAssets.lua").read_text()
CLIENT=(ROOT/"src/client/ApprovedVariantTowersLandmarkMeshKit.lua").read_text()
BUILDER=(ROOT/"src/server/MapBuilder.lua").read_text()
INIT=(ROOT/"src/server/init.server.lua").read_text()
LOD=(ROOT/"src/client/scenery-lod.client.lua").read_text()

entry=next(m for m in REG["models"] if m["name"]==NAME)
assert entry["asset_id"]==ID and entry["moderation"]=="Approved",entry
assert entry["workflow_run_id"]==RUN
assert entry["source"]=="tools/generate_original_variant_towers_machinery.py"
assert entry["source_materials"]=="assets/source/chaos_route_kit.mtl"
for source in (LOADER,CLIENT):
    assert ID in source
assert '"ApprovedVariantTowersLandmarkTemplates"' in LOADER
assert '"ApprovedVariantTowersLandmarkTemplates"' in CLIENT
assert 'OriginalMeshScenery.sanitize(raw)' in LOADER
assert 'task.wait(62)' in LOADER
assert 'if n ~= 7 then return false end' in LOADER
assert 'if count ~= 7 then return nil end' in CLIENT
assert 'ReplicatedStorage:FindFirstChild' in CLIENT
assert 'source:GetAttribute("Original3DAssetId") ~= ID' in CLIENT
assert 'source:GetAttribute("OwnerVerified") ~= true' in CLIENT
assert 'source:GetAttribute("CosmeticOnly") ~= true' in CLIENT
assert 'source:GetAttribute("OriginalTowersMachinery3D") ~= true' in CLIENT
assert 'source.DescendantRemoving:Connect' in CLIENT
assert 'clone.DescendantRemoving:Connect' in CLIENT

with tempfile.TemporaryDirectory(prefix="chaos-p4-towers-landmark-") as d:
    output=Path(d)/"original_towers_machinery.obj"
    p=subprocess.run([sys.executable,str(ROOT/"tools/generate_original_variant_towers_machinery.py"),
        "--output",str(output)],cwd=ROOT,capture_output=True,text=True,check=True)
    meta=json.loads(p.stdout)
    assert tuple(meta["bounds"])==(7.36,24.9,7.36),meta["bounds"]
    assert tuple(meta["center"])==(0.0,0.0,0.0),meta["center"]
    assert meta["triangles"]>900
    assert len(meta["materials"])==7
print("PASS source: original seven-material 7.36 x 24.9 x 7.36 sculpture")

# All four corners generated by the real gameplay map:
assert '"TowerMachinery" .. i' in BUILDER
assert '"TowerMachineryCap" .. i' in BUILDER
assert '"TowerAntenna" .. i' in BUILDER
for snippet in ('Vector3.new(-halfX - 6, 12, -halfZ - 6)',
                'Vector3.new(halfX + 6, 12, -halfZ - 6)',
                'Vector3.new(-halfX - 6, 12, halfZ + 6)',
                'Vector3.new(halfX + 6, 12, halfZ + 6)',
                'Vector3.new(5.2, 24, 5.2)',
                'Vector3.new(7.4, 1.0, 7.4)',
                'Vector3.new(0.55, 9, 0.55)'):
    assert snippet in BUILDER,snippet
for snippet in ('"TowerMachinery"..index','"TowerMachineryCap"..index',
                '"TowerAntenna"..index','Vector3.new(5.2,24,5.2)',
                'Vector3.new(7.4,1,7.4)','Vector3.new(.55,9,.55)',
                'x*(originalX*.5+6)','z*(originalZ*.5+6)',
                'center+Vector3.new(0,12.4,0)',
                'center+Vector3.new(0,17.2,0)',
                'body.Transparency=1','cap.LocalTransparencyModifier=1',
                'native.Transparency = alpha',
                'source.DescendantRemoving:Connect',
                'clone.DescendantRemoving:Connect',
                'piece.CanCollide=false','piece.CanTouch=false',
                'piece.CanQuery=false'):
    assert snippet in CLIENT,snippet
assert 'antenna.Transparency=1' not in CLIENT
assert 'antenna:Destroy()' not in CLIENT
assert CLIENT.index("clone.Parent=bucket")<CLIENT.index("body.Transparency=1")
# Two independent Low off-switches must BOTH be fixed: the tier cap and
# the mobile touch cap. At first GPU pressure one model becomes zero.
assert 'local CAP = {Low=1,Medium=2,High=4}' in CLIENT
assert 'local RANGE = {Low=220,Medium=290,High=410}' in CLIENT
assert 'or tier=="Low" and math.min(cap,1) or 0' in CLIENT
assert 'tier=="High" and math.min(cap,2)' in CLIENT
assert 'tier=="Medium" and math.min(cap,1)' in CLIENT
assert 'if stress==1 then cap=math.floor(cap*.5) end' in CLIENT
assert 'if stress>=2 then cap=0 end' in CLIENT
assert 'if cap==0 or not cameraReady' in CLIENT
assert 'local RETENTION = 24' in CLIENT
# A client budget eviction must immediately restore both the body and
# cap, while leaving the independently animated antenna untouched.
assert 'bucket.ChildRemoved:Connect(function(child)' in CLIENT
assert 'if entry.model==child then' in CLIENT
assert 'restore(body)' in CLIENT
assert CLIENT.index('mounted[body] = nil') < CLIENT.index('entry.model:Destroy()')
assert 'entry.cap.LocalTransparencyModifier=entry.capOriginalModifier' in CLIENT
assert 'entry.cap:SetAttribute("SceneryLodHidden",entry.capOriginalHidden)' in CLIENT
